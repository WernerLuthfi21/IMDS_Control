type ReportPart = {
  project?: string | null;
  part_no?: string | null;
  part_name?: string | null;
  imds_status?: string | null;
  submission_plan?: string | null;
  imds_id_version?: string | null;
  status_update?: string | null;
  md_id_version?: string | null;
  md_status_update_date?: string | null;
  comment?: string | null;
};

const ascii = (value: unknown) => String(value ?? "").normalize("NFKD").replace(/[^\x20-\x7E]/g, " ").replace(/\s+/g, " ").trim();
const pdfEscape = (value: string) => value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");

function wrap(text: string, max = 92): string[] {
  const words = ascii(text).split(" ");
  const lines: string[] = [];
  let line = "";
  for (const word of words) {
    const next = line ? line + " " + word : word;
    if (next.length > max && line) { lines.push(line); line = word; }
    else line = next;
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

export function buildSupplierReportPdf(supplierName: string, supplierCode: string, parts: ReportPart[]): Buffer {
  const pages: string[][] = [];
  let lines: string[] = [];
  let y = 790;
  const add = (text: string, size = 9, gap = 14) => {
    for (const wrapped of wrap(text, size >= 15 ? 70 : 92)) {
      if (y < 55) { pages.push(lines); lines = []; y = 790; }
      lines.push(`BT /F1 ${size} Tf 42 ${y} Td (${pdfEscape(wrapped)}) Tj ET`);
      y -= gap;
    }
  };
  add("IMDS SUBMISSION STATUS - SUPPLIER REPORT", 15, 24);
  add(`Supplier: ${supplierName}`, 11, 18);
  add(`Supplier code: ${supplierCode || "-"}`, 10, 17);
  add(`Generated: ${new Date().toISOString().slice(0, 10)}`, 9, 18);
  add(`Outstanding parts: ${parts.length}`, 10, 22);
  add("Please review the part list below and confirm the latest IMDS status and submission plan.", 9, 14);
  add(" ", 9, 8);
  parts.forEach((part, index) => {
    add(`${index + 1}. ${part.part_no || "-"} | ${part.project || "-"} | ${part.imds_status || "-"}`, 9, 14);
    add(`Part name: ${part.part_name || "-"}`, 8, 12);
    add(`Current IMDS ID / Version: ${part.imds_id_version || "-"} | Submission plan: ${part.submission_plan || "Not provided"}`, 8, 12);
    add(`MD System: ${part.status_update || "-"} | MD ID / Version: ${part.md_id_version || "-"} | Last changed: ${part.md_status_update_date || "-"}`, 8, 12);
    if (part.comment) add(`MD System comment: ${part.comment}`, 8, 12);
    add(" ", 8, 8);
  });
  add("Please reply with the confirmed status and target submission date for each outstanding part.", 9, 14);
  add("This report was generated by the IMDS Tracker workspace.", 8, 12);
  if (lines.length) pages.push(lines);

  const objects: string[] = [];
  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objects[2] = `<< /Type /Pages /Kids [${pages.map((_, i) => `${4 + i * 2} 0 R`).join(" ")}] /Count ${pages.length} >>`;
  objects[3] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";
  pages.forEach((page, index) => {
    const pageId = 4 + index * 2;
    const streamId = pageId + 1;
    const stream = page.join("\n");
    objects[pageId] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${streamId} 0 R >>`;
    objects[streamId] = `<< /Length ${Buffer.byteLength(stream, "ascii")} >>\nstream\n${stream}\nendstream`;
  });
  let pdf = "%PDF-1.4\n%IMDS\n";
  const offsets: number[] = [0];
  for (let i = 1; i < objects.length; i++) {
    offsets[i] = Buffer.byteLength(pdf, "ascii");
    pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(pdf, "ascii");
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let i = 1; i < objects.length; i++) pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(pdf, "ascii");
}
