const text = (v: unknown, max: number) => String(v ?? "").replace(/\r\n/g, "\n").slice(0, max);

/** Accepts whatever the browser sent and returns a safe, complete configuration. Unknown keys are dropped. */
function cleanNames(v: unknown, fallback: Record<string, string> = DEFAULT_SENDER_NAMES, max = 80): Record<string, string> {
  if (v === undefined) return { ...fallback };
  const out: Record<string, string> = {};
  if (!v || typeof v !== "object" || Array.isArray(v)) return out;
  for (const [k, n] of Object.entries(v as Record<string, unknown>).slice(0, 40)) {
    const key = text(k, 40).trim(), name = text(n, max).trim();
    if (key && name) out[key] = name;
  }
  return out;
}

export function sanitizeConfig(input: unknown): FollowupConfig {
  const src = (input && typeof input === "object" ? input : {}) as Record<string, unknown>;
  const seen = new Set<string>();
  const templates: Template[] = [];
  for (const t of Array.isArray(src.templates) ? src.templates.slice(0, 40) : []) {
    const o = (t && typeof t === "object" ? t : {}) as Record<string, unknown>;
    const id = text(o.id, 60).replace(/[^a-zA-Z0-9_-]/g, "") || `t${templates.length + 1}`;
    const kind = (KINDS as readonly string[]).includes(String(o.kind)) ? (o.kind as Kind) : "followup";
    const name = text(o.name, 80).trim(), subject = text(o.subject, 240).trim(), body = text(o.body, 12000).trim();
    if (!name || !subject || !body || seen.has(id)) continue;
    seen.add(id); templates.push({ id, kind, name, subject, body });
  }
  // Every kind always has at least one template, so the e-mail center can never be empty.
  for (const k of KINDS) if (!templates.some((t) => t.kind === k)) templates.push(...DEFAULT_CONFIG.templates.filter((t) => t.kind === k && !seen.has(t.id)));
  const wanted = (src.defaults && typeof src.defaults === "object" ? src.defaults : {}) as Record<string, unknown>;
  const defaults = {} as Record<Kind, string>;
  for (const k of KINDS) defaults[k] = (templates.find((t) => t.kind === k && t.id === wanted[k]) ?? templates.find((t) => t.kind === k)!).id;
  const roles = (src.ccRoles && typeof src.ccRoles === "object" ? src.ccRoles : {}) as Record<string, unknown>;
  const att = (src.attachments && typeof src.attachments === "object" ? src.attachments : {}) as Record<string, unknown>;
  const required = Array.isArray(src.requiredCc) ? src.requiredCc.join(";") : src.requiredCc === undefined ? DEFAULT_REQUIRED_CC.join(";") : String(src.requiredCc ?? "");
  return {
    templates, defaults,
    requiredCc: [...new Set(emailsOf(required))].slice(0, 30),
    ccRoles: { mid: roles.mid === true, top: roles.top === true, dir: roles.dir === true, buyer: roles.buyer === true },
    fallbackMid: src.fallbackMid !== false,
    attachments: { pdf: att.pdf !== false, xlsx: att.xlsx !== false },
    signature: src.signature === undefined ? DEFAULT_SIGNATURE : text(src.signature, 1000).trim(),
    senderNames: cleanNames(src.senderNames),
    senderFooters: cleanNames(src.senderFooters, {}, 1000),
    font: cleanFont(src.font),
    schedule: sanitizeSchedule(src.schedule)
  };
}

/** Required CC is always included; the sender's own address and anything already in `to` is dropped; no duplicates. */
export function mergeCc(input: { to: string[]; cc: string[]; required: string[]; senderEmail?: string | null }): string[] {
  const seen = new Set(input.to.map((e) => e.toLowerCase()));
  if (input.senderEmail) seen.add(input.senderEmail.toLowerCase());
  const out: string[] = [];
  for (const e of [...input.required, ...input.cc]) { const k = e.toLowerCase(); if (!seen.has(k)) { seen.add(k); out.push(e); } }
  return out;
}
