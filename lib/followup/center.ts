/** Adds the sign-off once: nothing is added when the body already ends with it (or has its own "regards"). */
export function withSignature(body: string, signature: string): string {
  const sig = String(signature || "").trim();
  if (!sig) return body;
  const first = sig.split("\n")[0].trim().toLowerCase();
  const tail = body.slice(-400).toLowerCase();
  if ((first && tail.includes(first)) || /\b(best|kind|warm) regards\b|\bsincerely\b/.test(tail)) return body;
  return body.replace(/\s+$/, "") + "\n\n" + sig;
}

/** Full name for a sender short name ("werner" → "Abdullah Luthfi Werner"); the short name itself when none is set. */
export function fullSenderName(names: Record<string, string>, sender?: string | null): string {
  const who = String(sender || "").trim();
  if (!who) return "";
  const hit = Object.keys(names).find((k) => k.toLowerCase() === who.toLowerCase());
  return (hit && names[hit]) || who;
}

/**
 * The configured sign-off with {sender}/{sendername} filled in, added once under the body.
 * A line that only held a placeholder is dropped when there is no sender, so no empty name line is sent.
 */
/** The sender's own footer when one is set (case-insensitive short name), else the shared signature. */
export function footerFor(cfg: Pick<FollowupConfig, "signature"> & Partial<Pick<FollowupConfig, "senderFooters">>, sender?: string | null): string {
  const who = String(sender || "").trim().toLowerCase(), own = cfg.senderFooters || {};
  const hit = who ? Object.keys(own).find((k) => k.toLowerCase() === who) : undefined;
  return (hit && own[hit]) || cfg.signature || "";
}

export function signOff(body: string, cfg: Pick<FollowupConfig, "signature" | "senderNames"> & Partial<Pick<FollowupConfig, "senderFooters">>, sender?: string | null): string {
  const who = String(sender || "").trim(), full = fullSenderName(cfg.senderNames || {}, who);
  const lines = footerFor(cfg, who).split("\n").map((l) => {
    const had = /\{sender(name)?\}/.test(l);
    const out = l.replace(/\{sendername\}/g, full).replace(/\{sender\}/g, who);
    return had && !out.trim() ? null : out;
  }).filter((l): l is string => l !== null);
  return withSignature(body, lines.join("\n").replace(/\n{3,}/g, "\n\n"));
}

