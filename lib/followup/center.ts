import { DEFAULT_SCHEDULE, sanitizeSchedule, type Schedule } from "./schedule";

export const KINDS = ["request", "followup", "recap"] as const;
export type Kind = (typeof KINDS)[number];
export const KIND_LABEL: Record<Kind, string> = { request: "Request (kick-off)", followup: "Follow-up (per supplier)", recap: "Status recap (all suppliers)" };

export type Template = { id: string; kind: Kind; name: string; subject: string; body: string };
export type FollowupConfig = {
  templates: Template[];
  /** The template pre-selected for each kind. */
  defaults: Record<Kind, string>;
  /** Always on CC for every e-mail. The sender cannot remove these; the server adds them again if missing. */
  requiredCc: string[];
  /** Directory contacts added to CC by default (the sender may switch them per batch, never the required list). */
  ccRoles: { mid: boolean; top: boolean; dir: boolean; buyer: boolean };
  /** When a supplier has no IMDS PIC e-mail, address middle management instead (the screen says so). */
  fallbackMid: boolean;
  /** Attachments generated by the server for every supplier e-mail. */
  attachments: { pdf: boolean; xlsx: boolean };
  /** Sign-off added under every e-mail (Power Automate sends have no Outlook signature). {sender} = chosen sender. */
  signature: string;
  /** Full name per sender shown in the sign-off ({sendername}), e.g. Werner → Abdullah Luthfi Werner. */
  senderNames: Record<string, string>;
  /** Footer per sender (short name → its own sign-off). When set it replaces `signature` for that sender. */
  senderFooters: Record<string, string>;
  /** Default font of the HTML e-mail body (Outlook renders this; the plain-text body is unchanged). */
  font: { family: string; sizePt: number };
  /** Weekly automatic follow-up (see lib/followup/schedule.ts). Off by default. */
  schedule: Schedule;
};

export const FONT_FAMILIES = ["Calibri", "Arial", "Segoe UI", "Verdana", "Tahoma", "Aptos", "Times New Roman"] as const;
export const DEFAULT_FONT = { family: "Calibri", sizePt: 11 };

/** Only a known family and a readable size (9–16 pt) are accepted, so the HTML never carries arbitrary CSS. */
export function cleanFont(v: unknown): { family: string; sizePt: number } {
  const o = (v && typeof v === "object" ? v : {}) as Record<string, unknown>;
  const fam = FONT_FAMILIES.find((f) => f.toLowerCase() === String(o.family ?? "").trim().toLowerCase()) ?? DEFAULT_FONT.family;
  const n = Math.round(Number(o.sizePt));
  return { family: fam, sizePt: Number.isFinite(n) && n >= 9 && n <= 16 ? n : DEFAULT_FONT.sizePt };
}

