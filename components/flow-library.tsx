"use client";
import { useMemo, useState, type ReactNode } from "react";
import { AlertTriangle, CircleCheck, CircleHelp, CircleX, Cog, FileWarning, Minus, Plus, Search } from "lucide-react";
import type { FlowChart, FlowChartNode } from "@/lib/judgement/flows";

type Group = { key: string; title: string; flows: FlowChart[] };

function groupOf(f: FlowChart): string {
  const n = Number(/^No\.(\d+)/.exec(f.title)?.[1]);
  if (n >= 10 && n <= 13) return "elv";
  if (Number.isFinite(n)) return "substance";
  return "other";
}
const GROUPS: Array<[string, string]> = [["elv", "ELV (Pb · Cd · Hg · Cr6+)"], ["substance", "Prohibited substances"], ["other", "Precedents and other charts"]];

/**
 * Rules → Flow charts. Every implemented judge flow drawn as a decision tree, generated by running
 * the engine itself (lib/judgement/flows.ts → flowChart), so what you see is exactly what judges a case.
 */
export function FlowLibrary({ charts, register }: { charts: FlowChart[]; register: ReactNode }) {
  const [tab, setTab] = useState<"flows" | "register">("flows");
  const [q, setQ] = useState("");
  const [sel, setSel] = useState(charts[0]?.id || "");
  const [zoom, setZoom] = useState(1);
  const groups = useMemo<Group[]>(() => {
    const term = q.trim().toLowerCase();
    const hit = charts.filter((c) => !term || (c.title + " " + c.source).toLowerCase().includes(term));
    return GROUPS.map(([key, title]) => ({ key, title, flows: hit.filter((c) => groupOf(c) === key) })).filter((g) => g.flows.length);
  }, [charts, q]);
  const chart = charts.find((c) => c.id === sel) || null;
  const counts = useMemo(() => chart ? tally(chart.root) : null, [chart]);

  return <div className="fl">
    <header className="fl-head">
      <div><span className="eyebrow">REFERENCE / RULES</span><h1 className="page-title">Judgement Rules</h1></div>
      <div className="fl-tabs" role="tablist" aria-label="Rules view">
        <button type="button" role="tab" aria-selected={tab === "flows"} className={tab === "flows" ? "on" : ""} onClick={() => setTab("flows")}>Flow charts ({charts.length})</button>
        <button type="button" role="tab" aria-selected={tab === "register"} className={tab === "register" ? "on" : ""} onClick={() => setTab("register")}>Error types &amp; sources</button>
      </div>
    </header>

    {tab === "register" ? <div className="fl-register">{register}</div> : <div className="fl-body">
      <nav className="fl-list" aria-label="Flows">
        <label className="fl-search"><Search size={14}/><input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Find a flow or substance…" aria-label="Find a flow"/></label>
        <div className="fl-scroll">
          {groups.map((g) => <section key={g.key}><h2>{g.title}</h2>
            {g.flows.map((f) => <button type="button" key={f.id} className={"fl-item" + (f.id === sel ? " on" : "")} aria-current={f.id === sel} onClick={() => { setSel(f.id); setZoom(1); }}>
              <span>{f.title}</span>
              <small>{f.page ? "p." + f.page : "—"}{f.draft && <em className="fl-draft">DRAFT</em>}</small>
            </button>)}
          </section>)}
          {!groups.length && <p className="fl-none">No flow matches “{q}”.</p>}
        </div>
      </nav>

      <section className="fl-canvas" aria-label={chart ? "Flow chart: " + chart.title : "Flow chart"}>
        {chart ? <>
          <div className="fl-canvas-head">
            <div>
              <h2>{chart.title}</h2>
              <p>{chart.source}{chart.page ? " · p." + chart.page : ""}</p>
            </div>
            <div className="fl-legend" aria-label="Legend">
              {counts && <><span className="ok"><CircleCheck size={13}/> {counts.OK} OK</span><span className="ng"><CircleX size={13}/> {counts.NG} NG</span><span className="hold"><AlertTriangle size={13}/> {counts.HOLD} TMC / hold</span></>}
              <span className="fl-zoom"><button type="button" onClick={() => setZoom((z) => Math.max(0.5, +(z - 0.1).toFixed(1)))} aria-label="Zoom out"><Minus size={14}/></button><b>{Math.round(zoom * 100)}%</b><button type="button" onClick={() => setZoom((z) => Math.min(1.4, +(z + 0.1).toFixed(1)))} aria-label="Zoom in"><Plus size={14}/></button></span>
            </div>
          </div>
          {chart.draft && <div className="fl-caution"><FileWarning size={14}/> {chart.caution || "Draft flow in the source: a person confirms every result; the system never finalises it."}</div>}
          {chart.truncated && <div className="fl-caution"><AlertTriangle size={14}/> This chart is very large; deep branches are cut off. Open a case to follow one path completely.</div>}
          <div className="fl-stage"><div className="fl-tree" style={{ zoom }}><Node n={chart.root} start/></div></div>
          <p className="fl-foot">Drawn from the same engine that judges cases. Questions answered by the row (content %, material, part name) are shown as questions here; on a real case they are filled in automatically.</p>
        </> : <p className="fl-none">Pick a flow.</p>}
      </section>
    </div>}
  </div>;
}

function tally(n: FlowChartNode, acc = { OK: 0, NG: 0, HOLD: 0 }) {
  if (n.outcome) acc[n.outcome.state]++;
  for (const b of n.branches) tally(b.node, acc);
  return acc;
}

function Node({ n, start }: { n: FlowChartNode; start?: boolean }) {
  return <div className="fl-node">
    {start && <span className="fl-start">Start</span>}
    {n.autos.map((a, i) => <div key={i} className="fl-auto"><Cog size={12}/> {a}</div>)}
    {n.question ? <div className="fl-q"><CircleHelp size={15}/><span>{n.question.text}</span></div>
      : n.outcome ? <div className={"fl-out " + n.outcome.state.toLowerCase()}>
        <strong>{n.outcome.state === "OK" ? <CircleCheck size={15}/> : n.outcome.state === "NG" ? <CircleX size={15}/> : <AlertTriangle size={15}/>}{n.outcome.state === "HOLD" ? "Contact TMC · hold" : "Judge " + n.outcome.state}</strong>
        <span>{n.outcome.comment || n.outcome.reason.replace(/^Flow result: Judge (OK|NG) — /, "")}</span></div>
      : null}
    {n.branches.length > 0 && <div className="fl-children">
      {n.branches.map((b, i) => <div className="fl-branch" key={i}>
        <span className="fl-label">{b.labels.join(" · ")}</span>
        <Node n={b.node}/>
      </div>)}
    </div>}
  </div>;
}
