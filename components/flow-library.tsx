"use client";
import { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState, type ReactNode } from "react";
import { useSearchParams } from "next/navigation";
import { AlertTriangle, CircleCheck, CircleHelp, CircleX, Cog, FileWarning, Maximize2, Minus, Plus, RotateCcw, Route, Search, X } from "lucide-react";
import type { FlowChart, FlowChartNode } from "@/lib/judgement/flows";
import { decodeTrail, tracePath, type TracedPath } from "@/lib/judgement/flow-path";

type Group = { key: string; title: string; flows: FlowChart[] };
type View = { x: number; y: number; z: number };

function groupOf(f: FlowChart): string {
  const n = Number(/^No\.(\d+)/.exec(f.title)?.[1]);
  if (n >= 10 && n <= 13) return "elv";
  if (Number.isFinite(n)) return "substance";
  return "other";
}
const GROUPS: Array<[string, string]> = [["elv", "ELV (Pb · Cd · Hg · Cr6+)"], ["substance", "Prohibited substances"], ["other", "Precedents and other charts"]];
const Z_MIN = 0.3, Z_MAX = 1.6;
const clampZ = (z: number) => Math.min(Z_MAX, Math.max(Z_MIN, +z.toFixed(2)));
const at = (root: FlowChartNode, key: string): FlowChartNode | null => {
  let n: FlowChartNode | undefined = root;
  for (const i of key.split(".").slice(1)) { n = n?.branches[Number(i)]?.node; if (!n) return null; }
  return n ?? null;
};

/**
 * Rules → Flow charts. Every implemented judge flow drawn as a decision tree, generated by running
 * the engine itself (lib/judgement/flows.ts → flowChart), so what you see is exactly what judges a case.
 * The canvas pans (drag, arrow keys), zooms (buttons, Ctrl + wheel, + / −), fits to the screen and
 * lights up one case's path when opened from a case (`?flow=<id>&trail=<encoded trail>`).
 */
export function FlowLibrary({ charts, register }: { charts: FlowChart[]; register: ReactNode }) {
  const [tab, setTab] = useState<"flows" | "register">("flows");
  const [q, setQ] = useState("");
  // Deep link from a case: /rules?flow=pfoa&trail=…&case=PART
  const params = useSearchParams();
  const linked = params.get("flow");
  const linkedOk = Boolean(linked && charts.some((c) => c.id === linked));
  const [sel, setSel] = useState(linkedOk ? linked! : charts[0]?.id || "");
  const [view, setView] = useState<View>({ x: 0, y: 0, z: 1 });
  const [picked, setPicked] = useState<string | null>(null);
  const [trail, setTrail] = useState<{ flow: string; steps: ReturnType<typeof decodeTrail>; label: string } | null>(() => {
    const steps = linkedOk ? decodeTrail(params.get("trail")) : [];
    return steps.length ? { flow: linked!, steps, label: params.get("case") || "" } : null;
  });
  const stage = useRef<HTMLDivElement>(null);
  const tree = useRef<HTMLDivElement>(null);
  const drag = useRef<{ x: number; y: number; vx: number; vy: number; moved: boolean } | null>(null);


  const groups = useMemo<Group[]>(() => {
    const term = q.trim().toLowerCase();
    const hit = charts.filter((c) => !term || (c.title + " " + c.source).toLowerCase().includes(term));
    return GROUPS.map(([key, title]) => ({ key, title, flows: hit.filter((c) => groupOf(c) === key) })).filter((g) => g.flows.length);
  }, [charts, q]);
  const chart = charts.find((c) => c.id === sel) || null;
  const counts = useMemo(() => chart ? tally(chart.root) : null, [chart]);
  const path: TracedPath | null = useMemo(() => chart && trail && trail.flow === chart.id ? tracePath(chart.root, trail.steps) : null, [chart, trail]);
  const onPath = useMemo(() => new Set(path?.nodes || []), [path]);
  const pathEnd = path ? at(chart!.root, path.nodes[path.nodes.length - 1]) : null;
  const pickedNode = chart && picked ? at(chart.root, picked) : null;

  const fit = useCallback(() => {
    const s = stage.current, t = tree.current;
    if (!s || !t) return;
    const pad = 32;
    // Fit, but never below a readable 55%: a big tree opens at its top and is panned, not shrunk to dots.
    const z = Math.max(0.55, clampZ(Math.min(1, (s.clientWidth - pad) / t.offsetWidth, (s.clientHeight - pad) / t.offsetHeight)));
    setView({ z, x: Math.max(pad / 2, (s.clientWidth - t.offsetWidth * z) / 2), y: pad / 2 });
  }, []);
  // a new chart opens fitted to the screen
  useLayoutEffect(() => { fit(); }, [sel, tab, fit]);
  const openFlow = (id: string) => { setSel(id); setPicked(null); };
  useEffect(() => { const on = () => fit(); window.addEventListener("resize", on); return () => window.removeEventListener("resize", on); }, [fit]);

  /** Zoom around a point of the stage (default: its centre). */
  const zoomBy = useCallback((f: number, cx?: number, cy?: number) => {
    const s = stage.current; if (!s) return;
    const px = cx ?? s.clientWidth / 2, py = cy ?? s.clientHeight / 2;
    setView((v) => { const z = clampZ(v.z * f); const k = z / v.z; return { z, x: px - (px - v.x) * k, y: py - (py - v.y) * k }; });
  }, []);
  // Ctrl/⌘ + wheel zooms; a plain wheel pans (so trackpads and mice both work). Non-passive to stop page zoom.
  useEffect(() => {
    const s = stage.current; if (!s) return;
    const onWheel = (e: WheelEvent) => {
      e.preventDefault();
      if (e.ctrlKey || e.metaKey) { const r = s.getBoundingClientRect(); zoomBy(Math.exp(-e.deltaY * 0.0022), e.clientX - r.left, e.clientY - r.top); }
      else setView((v) => ({ ...v, x: v.x - (e.shiftKey ? e.deltaY : e.deltaX), y: v.y - (e.shiftKey ? 0 : e.deltaY) }));
    };
    s.addEventListener("wheel", onWheel, { passive: false });
    return () => s.removeEventListener("wheel", onWheel);
  }, [zoomBy, chart, tab]);

  const focusPath = () => {
    const s = stage.current; if (!s || !path) return;
    const el = s.querySelector<HTMLElement>(`[data-k="${path.nodes[path.nodes.length - 1]}"]`);
    if (!el) return;
    const sr = s.getBoundingClientRect(), er = el.getBoundingClientRect();
    setView((v) => ({ ...v, x: v.x + (sr.left + sr.width / 2) - (er.left + er.width / 2), y: v.y + (sr.top + sr.height / 2) - (er.top + er.height / 2) }));
    setPicked(path.nodes[path.nodes.length - 1]);
  };
  // Opened from a case: bring the end of its path into view once the chart is laid out.
  const focused = useRef(false);
  useEffect(() => {
    if (focused.current || !path || !chart || trail?.flow !== chart.id) return;
    focused.current = true;
    const id = window.requestAnimationFrame(() => focusPath());
    return () => window.cancelAnimationFrame(id);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [path, chart]);

  return <div className="fl">
    <header className="fl-head">
      <div><span className="eyebrow">REFERENCE / RULES</span><h1 className="page-title">Judgement Rules</h1></div>
      <div className="fl-tabs" role="tablist" aria-label="Rules view">
        <button type="button" role="tab" aria-selected={tab === "flows"} className={tab === "flows" ? "on" : ""} onClick={() => setTab("flows")}>Flow charts ({charts.length})</button>
        <button type="button" role="tab" aria-selected={tab === "register"} className={tab === "register" ? "on" : ""} onClick={() => setTab("register")}>Error types &amp; sources</button>
      </div>
    </header>

    {tab === "register" ? <div className="fl-register">{register}</div> : <div className="fl-body">
      <nav className="fl-list" aria-label="Flows">
        <label className="fl-search"><Search size={14} aria-hidden="true"/><input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Find a flow or substance…" aria-label="Find a flow"/></label>
        <div className="fl-scroll">
          {groups.map((g) => <section key={g.key}><h2>{g.title}</h2>
            {g.flows.map((f) => <button type="button" key={f.id} className={"fl-item" + (f.id === sel ? " on" : "")} aria-current={f.id === sel} onClick={() => openFlow(f.id)}>
              <span>{f.title}</span>
              <small>{f.page ? "p." + f.page : "—"}{f.draft && <em className="fl-draft">DRAFT</em>}{trail?.flow === f.id && <em className="fl-pathtag">CASE PATH</em>}</small>
            </button>)}
          </section>)}
          {!groups.length && <p className="fl-none">No flow matches “{q}”.</p>}
        </div>
      </nav>

      <section className="fl-canvas" aria-label={chart ? "Flow chart: " + chart.title : "Flow chart"}>
        {chart ? <>
          <div className="fl-canvas-head">
            <div>
              <h2>{chart.title}</h2>
              <p>{chart.source}{chart.page ? " · p." + chart.page : ""}</p>
            </div>
            <div className="fl-legend" aria-label="Legend">
              {counts && <><span className="ok"><CircleCheck size={13} aria-hidden="true"/> {counts.OK} OK</span><span className="ng"><CircleX size={13} aria-hidden="true"/> {counts.NG} NG</span><span className="hold"><AlertTriangle size={13} aria-hidden="true"/> {counts.HOLD} TMC / hold</span></>}
              <span className="fl-zoom" role="group" aria-label="Zoom">
                <button type="button" onClick={() => zoomBy(1 / 1.2)} aria-label="Zoom out" title="Zoom out (−)"><Minus size={14}/></button>
                <b aria-live="polite">{Math.round(view.z * 100)}%</b>
                <button type="button" onClick={() => zoomBy(1.2)} aria-label="Zoom in" title="Zoom in (+)"><Plus size={14}/></button>
                <button type="button" onClick={fit} aria-label="Fit to screen" title="Fit to screen (F)"><Maximize2 size={14}/></button>
                <button type="button" onClick={() => setView({ x: 16, y: 16, z: 1 })} aria-label="Reset to 100%" title="Reset to 100% (0)"><RotateCcw size={14}/></button>
              </span>
            </div>
          </div>
          {chart.draft && <div className="fl-caution"><FileWarning size={14} aria-hidden="true"/> {chart.caution || "Draft flow in the source: a person confirms every result; the system never finalises it."}</div>}
          {chart.truncated && <div className="fl-caution"><AlertTriangle size={14} aria-hidden="true"/> This chart is very large; deep branches are cut off. Open a case to follow one path completely.</div>}
          {path && <div className={"fl-pathbar" + (path.complete ? "" : " open")} role="status">
            <Route size={15} aria-hidden="true"/>
            <span><b>Case path{trail?.label ? " · " + trail.label : ""}</b> — {path.matched} step{path.matched === 1 ? "" : "s"} matched{path.complete && pathEnd?.outcome ? `, ends at ${pathEnd.outcome.state === "HOLD" ? "TMC / hold" : "Judge " + pathEnd.outcome.state}` : pathEnd?.question ? `, waiting at “${pathEnd.question.text}”` : ", path could not be followed further on this chart"}.</span>
            <button type="button" className="fl-pathbtn" onClick={focusPath}>Show</button>
            <button type="button" className="fl-pathx" onClick={() => setTrail(null)} aria-label="Clear the case path"><X size={14}/></button>
          </div>}
          <div className="fl-work">
            <div ref={stage} className="fl-stage" tabIndex={0} role="group"
              aria-label="Flow chart canvas. Drag or use arrow keys to pan, plus and minus to zoom, F to fit, 0 to reset."
              onPointerDown={(e) => { if (e.button !== 0) return; drag.current = { x: e.clientX, y: e.clientY, vx: view.x, vy: view.y, moved: false }; }}
              onPointerMove={(e) => {
                const d = drag.current; if (!d) return;
                const dx = e.clientX - d.x, dy = e.clientY - d.y;
                if (!d.moved && Math.hypot(dx, dy) < 4) return;
                if (!d.moved) { d.moved = true; (e.currentTarget as HTMLElement).setPointerCapture(e.pointerId); e.currentTarget.classList.add("grabbing"); }
                setView((v) => ({ ...v, x: d.vx + dx, y: d.vy + dy }));
              }}
              onPointerUp={(e) => { e.currentTarget.classList.remove("grabbing"); window.setTimeout(() => { drag.current = null; }, 0); }}
              onPointerCancel={(e) => { e.currentTarget.classList.remove("grabbing"); drag.current = null; }}
              onKeyDown={(e) => {
                const step = 60;
                if (e.target !== e.currentTarget) return;
                if (e.key === "ArrowLeft") setView((v) => ({ ...v, x: v.x + step }));
                else if (e.key === "ArrowRight") setView((v) => ({ ...v, x: v.x - step }));
                else if (e.key === "ArrowUp") setView((v) => ({ ...v, y: v.y + step }));
                else if (e.key === "ArrowDown") setView((v) => ({ ...v, y: v.y - step }));
                else if (e.key === "+" || e.key === "=") zoomBy(1.2);
                else if (e.key === "-" || e.key === "_") zoomBy(1 / 1.2);
                else if (e.key.toLowerCase() === "f") fit();
                else if (e.key === "0") setView({ x: 16, y: 16, z: 1 });
                else return;
                e.preventDefault();
              }}>
              <div ref={tree} className={"fl-tree" + (path ? " has-path" : "")} style={{ transform: `translate(${view.x}px, ${view.y}px) scale(${view.z})` }}>
                <Node n={chart.root} k="r" start onPath={onPath} picked={picked} onPick={(k) => { if (!drag.current?.moved) setPicked((p) => p === k ? null : k); }}/>
              </div>
            </div>
            <NodeDetail chart={chart} k={picked} node={pickedNode} onPath={picked ? onPath.has(picked) : false} onClose={() => setPicked(null)}/>
          </div>
          <p className="fl-foot">Drawn from the same engine that judges cases. Questions answered by the row (content %, material, part name) are shown as questions here; on a real case they are filled in automatically.</p>
        </> : <p className="fl-none">Pick a flow.</p>}
      </section>
    </div>}
  </div>;
}

function tally(n: FlowChartNode, acc = { OK: 0, NG: 0, HOLD: 0 }) {
  if (n.outcome) acc[n.outcome.state]++;
  for (const b of n.branches) tally(b.node, acc);
  return acc;
}

const outcomeTitle = (s: "OK" | "NG" | "HOLD") => s === "HOLD" ? "Contact TMC · hold" : "Judge " + s;
const outcomeText = (o: NonNullable<FlowChartNode["outcome"]>) => o.comment || o.reason.replace(/^Flow result: Judge (OK|NG) — /, "");

function NodeDetail({ chart, k, node, onPath, onClose }: { chart: FlowChart; k: string | null; node: FlowChartNode | null; onPath: boolean; onClose: () => void }) {
  if (!node || !k) return <aside className="fl-detail empty" aria-label="Step details"><p>Select a question or result in the chart to see its answers, what follows, and where it comes from.</p><p className="fl-keys"><kbd>Drag</kbd> pan · <kbd>Ctrl</kbd>+wheel zoom · <kbd>F</kbd> fit · <kbd>0</kbd> 100%</p></aside>;
  const depth = k.split(".").length - 1;
  return <aside className="fl-detail" aria-label="Step details">
    <div className="fl-detail-head"><span className="eyebrow">{node.question ? "QUESTION" : "RESULT"} · STEP {depth + 1}</span><button type="button" onClick={onClose} aria-label="Close details"><X size={14}/></button></div>
    {node.question ? <h3>{node.question.text}</h3> : node.outcome ? <h3 className={"fl-dout " + node.outcome.state.toLowerCase()}>{outcomeTitle(node.outcome.state)}</h3> : null}
    {node.outcome && <p>{outcomeText(node.outcome)}</p>}
    {onPath && <p className="fl-onpath"><Route size={13} aria-hidden="true"/> On this case&apos;s path</p>}
    {node.autos.length > 0 && <><h4>Checked automatically before this step</h4><ul>{node.autos.map((a, i) => <li key={i}>{a}</li>)}</ul></>}
    {node.branches.length > 0 && <><h4>Answers</h4><ul className="fl-dans">{node.branches.map((b, i) => {
      const t = tally(b.node);
      const leaf = b.node.outcome;
      return <li key={i}><b>{b.labels.join(" · ")}</b><span>{leaf ? outcomeTitle(leaf.state) : b.node.question ? "→ " + b.node.question.text : "—"}</span>{!leaf && <small>{t.OK} OK · {t.NG} NG · {t.HOLD} hold below</small>}</li>;
    })}</ul></>}
    <h4>Source</h4><p className="fl-dsrc">{chart.source}{chart.page ? ", p." + chart.page : ""}{chart.draft ? " · draft (people confirm)" : ""}</p>
  </aside>;
}

function Node({ n, k, start, onPath, picked, onPick }: { n: FlowChartNode; k: string; start?: boolean; onPath: Set<string>; picked: string | null; onPick: (k: string) => void }) {
  const on = onPath.has(k);
  const cls = (base: string) => base + (on ? " on-path" : "") + (picked === k ? " picked" : "");
  return <div className="fl-node">
    {start && <span className={"fl-start" + (on ? " on-path" : "")}>Start</span>}
    {n.autos.map((a, i) => <div key={i} className={"fl-auto" + (on ? " on-path" : "")}><Cog size={12} aria-hidden="true"/> {a}</div>)}
    {n.question ? <button type="button" data-k={k} className={cls("fl-q")} aria-pressed={picked === k} onClick={() => onPick(k)}><CircleHelp size={15} aria-hidden="true"/><span>{n.question.text}</span></button>
      : n.outcome ? <button type="button" data-k={k} className={cls("fl-out " + n.outcome.state.toLowerCase())} aria-pressed={picked === k} onClick={() => onPick(k)}>
        <strong>{n.outcome.state === "OK" ? <CircleCheck size={15} aria-hidden="true"/> : n.outcome.state === "NG" ? <CircleX size={15} aria-hidden="true"/> : <AlertTriangle size={15} aria-hidden="true"/>}{outcomeTitle(n.outcome.state)}</strong>
        <span>{outcomeText(n.outcome)}</span></button>
      : null}
    {n.branches.length > 0 && <div className="fl-children">
      {n.branches.map((b, i) => { const ck = k + "." + i; return <div className={"fl-branch" + (onPath.has(ck) ? " on-path" : "")} key={i}>
        <span className="fl-label">{b.labels.join(" · ")}</span>
        <Node n={b.node} k={ck} onPath={onPath} picked={picked} onPick={onPick}/>
      </div>; })}
    </div>}
  </div>;
}
